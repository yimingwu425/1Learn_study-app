from playwright.sync_api import sync_playwright
from pathlib import Path
out=Path(__file__).parent/'ui';out.mkdir(exist_ok=True)
with sync_playwright() as p:
 b=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 page=b.new_page(viewport={"width":1440,"height":1000},device_scale_factor=1)
 page.goto('http://127.0.0.1:5173')
 page.wait_for_timeout(1000)
 page.screenshot(path=str(out/'home.png'),full_page=True)
 page.get_by_role('button',name='体验学习桌').click()
 page.get_by_role('button',name='提示',exact=True).click()
 page.screenshot(path=str(out/'study.png'),full_page=True)
 page.get_by_role('button',name='再给一点提示').click()
 assert '6.0 Ω' in page.locator('.guide').inner_text()
 page.get_by_role('button',name='做完了').click()
 page.get_by_label('我的笔记').fill('测试：内阻和外电阻串联')
 page.get_by_role('button',name='提示后会了').click()
 page.get_by_role('button',name='我的资料',exact=True).click()
 assert '测试：内阻和外电阻串联' in page.locator('.notes-list').inner_text()
 page.get_by_role('button',name='导入题目',exact=True).click()
 page.screenshot(path=str(out/'import.png'),full_page=True)
 page.set_viewport_size({'width':390,'height':844})
 page.get_by_role('button',name='学习',exact=True).click()
 page.get_by_role('button',name='体验学习桌').click()
 page.screenshot(path=str(out/'mobile-study.png'),full_page=True)
 assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
 print('PASS demo study/hint/mark/note/navigation/mobile layout')
 b.close()
